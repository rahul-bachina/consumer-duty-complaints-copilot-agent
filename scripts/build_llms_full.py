#!/usr/bin/env python3
"""Concatenate the README and the key docs into llms-full.txt.

    python scripts/build_llms_full.py
    python scripts/build_llms_full.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "llms-full.txt"

PARTS = (
    "README.md",
    "docs/architecture.md",
    "docs/security-and-permissions.md",
    "docs/foundry.md",
    "docs/harness-comparison.md",
    "docs/github-copilot-harness.md",
    "docs/dynamics-365-customer-service.md",
    "docs/autonomy-levels.md",
    "copilot-studio/README.md",
    "copilot-studio/system-prompt.md",
    "agent-manifest.yaml",
)


def render() -> str:
    blocks = [
        "FCA Consumer Duty Complaint Handling AI Agent",
        "",
        "This file concatenates the README and the key documents so a language",
        "model can read them in one request. It is generated by",
        "scripts/build_llms_full.py. The shorter index is llms.txt.",
        "Synthetic complaints only. The agent never decides a complaint outcome.",
        "",
    ]
    for relative in PARTS:
        path = ROOT / relative
        if not path.is_file():
            raise SystemExit(f"Missing {relative}")
        blocks.append("=" * 72)
        blocks.append(f"FILE: {relative}")
        blocks.append("=" * 72)
        blocks.append("")
        blocks.append(path.read_text(encoding="utf-8").rstrip())
        blocks.append("")
    return "\n".join(blocks).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if llms-full.txt is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print("llms-full.txt is out of date. Run: python scripts/build_llms_full.py", file=sys.stderr)
            return 1
        print("llms-full.txt matches the source documents.")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(text)} characters).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
